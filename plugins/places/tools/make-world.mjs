// Generates src/world-data.js: the precomputed parts of the Dream map's world.
//   node plugins/places/tools/make-world.mjs
// Inputs are Natural Earth data (public domain) from the world-atlas package.
// Nothing here runs in Buzz; the plugin bundles the output.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoArea, geoCentroid, geoContains, geoNaturalEarth1 } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const here = new URL(".", import.meta.url).pathname;
const world110 = require("world-atlas/countries-110m.json");
const world50 = require("world-atlas/countries-50m.json");
const land110 = feature(world110, world110.objects.land);

// Int16 pairs as base64: compact, and decoded once when a look needs them.
function pack(pairs, scale) {
  const buffer = Buffer.alloc(pairs.length * 4);
  pairs.forEach(([a, b], i) => {
    buffer.writeInt16LE(Math.round(a * scale), i * 4);
    buffer.writeInt16LE(Math.round(b * scale), i * 4 + 2);
  });
  return buffer.toString("base64");
}

// Flat dots: an even grid in Natural Earth projected space, kept where it
// falls on land. Stored in reference units; the map rescales them.
const REF_WIDTH = 1000;
const STEP = 6;
const flat = geoNaturalEarth1().fitWidth(REF_WIDTH, { type: "Sphere" });
const sphereBounds = [flat([-180, 0])[0], flat([0, 90])[1], flat([180, 0])[0], flat([0, -90])[1]];
const flatDots = [];
for (let y = STEP / 2; y < sphereBounds[3]; y += STEP) {
  for (let x = STEP / 2; x < REF_WIDTH; x += STEP) {
    const point = flat.invert([x, y]);
    if (!point || !Number.isFinite(point[0])) continue;
    const back = flat(point);
    if (!back || Math.hypot(back[0] - x, back[1] - y) > 0.5) continue; // outside the sphere outline
    if (geoContains(land110, point)) flatDots.push([x, y]);
  }
}

// Globe dots: a Fibonacci sphere, so dots are evenly spaced on the globe.
const N = 16000;
const golden = Math.PI * (3 - Math.sqrt(5));
const globeDots = [];
for (let i = 0; i < N; i++) {
  const z = 1 - (2 * (i + 0.5)) / N;
  const lat = (Math.asin(z) * 180) / Math.PI;
  const lng = ((((i * golden * 180) / Math.PI) % 360) + 540) % 360 - 180;
  if (geoContains(land110, [lng, lat])) globeDots.push([lat, lng]);
}

// A curved country (Vietnam) or one around a hole (Israel) can have its
// centroid outside it: take the inside point nearest the centroid instead.
// Atolls too small to sample keep the average of their outline.
function interiorPoint(polygon, [cx, cy]) {
  const ring = polygon.coordinates[0];
  const xs = ring.map((p) => p[0]);
  const ys = ring.map((p) => p[1]);
  const [x0, x1, y0, y1] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
  let best;
  for (let i = 0; i <= 80; i++) {
    for (let j = 0; j <= 80; j++) {
      const point = [x0 + ((x1 - x0) * i) / 80, y0 + ((y1 - y0) * j) / 80];
      if (!geoContains(polygon, point)) continue;
      const d = Math.hypot(point[0] - cx, point[1] - cy);
      if (!best || d < best.d) best = { point, d };
    }
  }
  if (best) return best.point;
  return [xs.reduce((a, b) => a + b) / xs.length, ys.reduce((a, b) => a + b) / ys.length];
}

// A representative point per country: the centroid of its largest polygon,
// so France means mainland France and the US means the lower 48.
const countries = [];
for (const country of feature(world50, world50.objects.countries).features) {
  const name = country.properties?.name;
  if (!name || !country.geometry) continue;
  const polygons =
    country.geometry.type === "MultiPolygon"
      ? country.geometry.coordinates.map((coordinates) => ({ type: "Polygon", coordinates }))
      : [country.geometry];
  const largest = polygons.reduce((best, polygon) => (geoArea(polygon) > geoArea(best) ? polygon : best));
  let [lng, lat] = geoCentroid(largest);
  if (!geoContains(largest, [lng, lat])) [lng, lat] = interiorPoint(largest, [lng, lat]);
  countries.push([name, Number(lat.toFixed(2)), Number(lng.toFixed(2))]);
}
countries.sort((a, b) => a[0].localeCompare(b[0]));

const out = `// Generated by tools/make-world.mjs from Natural Earth (public domain) via
// world-atlas. Do not edit by hand.
export const FLAT_DOTS = { width: ${REF_WIDTH}, height: ${sphereBounds[3].toFixed(2)}, step: ${STEP}, count: ${flatDots.length}, data: "${pack(flatDots, 10)}" };
export const GLOBE_DOTS = { count: ${globeDots.length}, data: "${pack(globeDots, 100)}" };
export const COUNTRIES = ${JSON.stringify(countries)};
`;
writeFileSync(`${here}../src/world-data.js`, out);
const kib = (Buffer.byteLength(out) / 1024).toFixed(1);
console.log(`world-data.js: ${flatDots.length} flat dots, ${globeDots.length} globe dots, ${countries.length} countries, ${kib} KiB`);
void readFileSync;
